#!/usr/bin/env python3
"""Writes src/lib/pace/official.ts from the checked CMS index files (internal only; never in a public build).
  PACE county + ESRD rates:      /workspace/healthcare-pfs/index/pace_history.sqlite
  Part D:                        /workspace/healthcare-pfs/index/ma_partd_ny.sqlite
Nothing is estimated: a county/year missing from the files is simply absent, and the screen says 'not yet checked against CMS'.
Usage: python3 scripts/build-pace-rates.py [--check]"""
import json, sqlite3, sys
from decimal import Decimal
IDX = "/workspace/healthcare-pfs/index"
OUT = "src/lib/pace/official.ts"
import os
if "--check" in sys.argv and not os.path.exists(f"{IDX}/pace_history.sqlite"):
    print("pace rates: SKIP, CMS index files not on this machine"); sys.exit(0)
def cents(v): return int((Decimal(str(v)) * 100).to_integral_value())
pace = sqlite3.connect(f"file:{IDX}/pace_history.sqlite?mode=ro", uri=True)
ma = sqlite3.connect(f"file:{IDX}/ma_partd_ny.sqlite?mode=ro", uri=True)
out = {"note": "Generated by scripts/build-pace-rates.py from pace_history.sqlite and ma_partd_ny.sqlite. Monthly amounts in cents.",
       "pace": {}, "paceEsrd": {}, "partD": {}}
url = dict(pace.execute("select id, source_url from sources"))
# Every New York county in the PACE ratebook (62). A county missing for a year is simply absent and reads NOT_CHECKED.
COUNTIES = sorted({c.title() for (c,) in pace.execute("select distinct county from pace_county_rates where year between 2020 and 2027 and state in ('NEW YORK','NY')")})
out["counties"] = COUNTIES
for year, county, risk, esrd, member, sid in pace.execute(
        "select year, county, risk_ab, esrd_ab, member, source_id from pace_county_rates where year between 2020 and 2027 and state in ('NEW YORK','NY') and period_id=cast(year as text) order by year"):
    name = county.title()
    if name not in COUNTIES: continue
    src = f"CMS PACE ratebook {year} ({member.split('/')[-1]}), {url[sid]}"
    out["pace"].setdefault(str(year), {})[name] = {"cents": cents(risk), "source": src}
    out["paceEsrd"].setdefault(str(year), {})[name] = {"cents": cents(esrd), "source": src}
# 2020 PACE ESRD was revised by CMS on 2020-10-02. Both values are kept; src/lib/pace/rates.ts (ESRD_2020_USE) picks one.
out["paceEsrdRevised"] = {}
for year, county, rev, member, sid in pace.execute(
        "select year, county, revised_esrd_ab, member, source_id from pace_esrd_revised where year between 2020 and 2027"):
    name = county.title()
    if name in COUNTIES and str(year) in out["paceEsrd"]:
        out["paceEsrdRevised"].setdefault(str(year), {})[name] = {"cents": cents(rev), "source": f"CMS revised PACE ESRD rates {year}, released 2020-10-02 ({member}), {url[sid]}"}
rel = {i: (t, u) for i, t, u in ma.execute("select id, title, source_url from releases")}
# The MA file's statewide ESRD rate is deliberately not taken: PACE ESRD comes from the PACE ratebook only.
for year, bid, prem, rid, page in ma.execute("select year, national_avg_monthly_bid, base_beneficiary_premium, release_id, page from partd_params"):
    out["partD"][str(year)] = {"bidCents": cents(bid), "premiumCents": cents(prem), "source": f"{rel[rid][0]}, page {page}, {rel[rid][1]}"}
# Years the MA/Part D file does not cover (2027) come from pace_history.sqlite's Part D table, with its own quote.
for year, bid, prem, sid, page in pace.execute("select year, national_avg_monthly_bid, base_beneficiary_premium, source_id, bid_page from partd where year between 2020 and 2027"):
    if str(year) not in out["partD"]:
        out["partD"][str(year)] = {"bidCents": cents(bid), "premiumCents": cents(prem), "source": f"CMS CY{year} Part D national average bid / base premium memo, page {page}, {url[sid]}"}
for k in ("pace", "paceEsrd", "paceEsrdRevised", "partD"): out[k] = dict(sorted(out[k].items()))
text = "// Generated by scripts/build-pace-rates.py. Do not edit by hand. Internal only.\nexport const OFFICIAL = " + json.dumps(out, indent=1) + ";\n"
if "--check" in sys.argv:
    same = open(OUT).read() == text
    print("pace rates: official.ts matches the CMS index files" if same else "pace rates: official.ts differs from the CMS index files")
    sys.exit(0 if same else 1)
open(OUT, "w").write(text)
print("wrote", OUT, {k: len(v) for k, v in out.items() if isinstance(v, dict)})
